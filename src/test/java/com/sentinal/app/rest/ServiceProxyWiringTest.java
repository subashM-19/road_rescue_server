package com.sentinal.app.rest;

import com.sentinal.persistencefw.PersistenceManager;
import com.sentinal.persistencefw.metadata.ColumnMetaData;
import com.sentinal.persistencefw.metadata.Schema;
import com.sentinal.persistencefw.transaction.TransactionManager;
import com.sentinal.persistencefw.transaction.TransactionProxy;
import com.sentinal.roadrescue.notification.NotificationService;
import com.sentinal.roadrescue.notification.NotificationType;
import com.sentinal.roadrescue.notification.NotificationWriterOperations;
import org.junit.jupiter.api.*;
import java.sql.*;
import java.lang.reflect.*;
import static org.junit.jupiter.api.Assertions.*;

class ServiceProxyWiringTest
{
    private static final String URL = "jdbc:h2:mem:persistence_test;DB_CLOSE_DELAY=-1";
    public interface BusinessWork { void run(); }

    @BeforeEach void setup() throws Exception
    {
        PersistenceManager.initialize(URL, "sa", "");
        Schema.clear();
        try (Connection c = DriverManager.getConnection(URL, "sa", ""); Statement s = c.createStatement())
        {
            s.execute("DROP ALL OBJECTS");
            s.execute("CREATE TABLE Notification (NotificationID BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, UserID BIGINT, NotificationType INT, Title VARCHAR(255), Message VARCHAR(1000), Status INT, CreatedTime BIGINT, LastModifiedTime BIGINT)");
        }
        Schema.registerTable("Notification",
            column("NotificationID", Types.BIGINT, true), column("UserID", Types.BIGINT, false),
            column("NotificationType", Types.INTEGER, false), column("Title", Types.VARCHAR, false),
            column("Message", Types.VARCHAR, false), column("Status", Types.INTEGER, false),
            column("CreatedTime", Types.BIGINT, false), column("LastModifiedTime", Types.BIGINT, false));
    }

    private ColumnMetaData column(String name, int type, boolean key)
    {
        return new ColumnMetaData(name, type, type == Types.VARCHAR ? "VARCHAR" : type == Types.INTEGER ? "INTEGER" : "BIGINT", 1000, false, key, key, key, null, false, null, null);
    }

    @AfterEach void cleanup()
    {
        assertFalse(TransactionManager.isActive());
        Schema.clear();
    }

    private int count() throws SQLException
    {
        try (Connection c = DriverManager.getConnection(URL, "sa", ""); Statement s = c.createStatement(); ResultSet r = s.executeQuery("SELECT COUNT(*) FROM Notification"))
        {
            r.next(); return r.getInt(1);
        }
    }

    @Test void everyBusinessGetterReturnsACachedInterfaceProxy() throws Exception
    {
        String[][] getters = {
            {"com.sentinal.roadrescue.admin.MechanicAdminAPI", "getMechanicAdminImpl"},
            {"com.sentinal.roadrescue.admin.MechanicShopAPI", "getMechanicShopImpl"},
            {"com.sentinal.roadrescue.admin.ServiceRequestAdminAPI", "getServiceRequestAdminImpl"},
            {"com.sentinal.roadrescue.admin.UserAdminAPI", "getUserAdminImpl"},
            {"com.sentinal.roadrescue.common.CurrentUserAPI", "getCurrentUserImpl"},
            {"com.sentinal.roadrescue.dispatch.AutoAssignmentService", "getAutoAssignmentImpl"},
            {"com.sentinal.roadrescue.mechanic.MechanicAPI", "getMechanicImpl"},
            {"com.sentinal.roadrescue.mechanic.MechanicApplicationAPI", "getMechanicImpl"},
            {"com.sentinal.roadrescue.mechanic.MechanicAssignmentAPI", "getMechanicAssignmentImpl"},
            {"com.sentinal.roadrescue.mechanic.MechanicAvailabilityAPI", "getMechanicAvailabilityImpl"},
            {"com.sentinal.roadrescue.mechanic.MechanicIdentityService", "getMechanicIdentityImpl"},
            {"com.sentinal.roadrescue.mechanic.MechanicShopManagementAPI", "getMechanicShopManagementImpl"},
            {"com.sentinal.roadrescue.notification.NotificationAPI", "getNotificationImpl"},
            {"com.sentinal.roadrescue.notification.NotificationService", "getNotificationWriterImpl"},
            {"com.sentinal.roadrescue.realtime.TrackingService", "getTrackingImpl"},
            {"com.sentinal.roadrescue.security.UserIdentityService", "getUserIdentityImpl"},
            {"com.sentinal.roadrescue.service.ServiceRequestAPI", "getServiceRequestImpl"}
        };
        for (String[] entry : getters)
        {
            Method getter = Class.forName(entry[0]).getMethod(entry[1]);
            Object proxy = getter.invoke(null);
            assertTrue(getter.getReturnType().isInterface(), entry[0]);
            assertTrue(Proxy.isProxyClass(proxy.getClass()), entry[0]);
            assertSame(proxy, getter.invoke(null), entry[0]);
        }
    }

    @Test void facadeCommitsThroughActualNotificationImplementation() throws Exception
    {
        new NotificationService().create(1, NotificationType.MECHANIC_APPLICATION_APPROVED, "Approved", "Welcome");
        assertEquals(1, count());
    }

    @Test void collaboratingProxySharesTheOwnersTransactionAndRollsBack()
    {
        NotificationWriterOperations notifications = NotificationService.getNotificationWriterImpl();
        BusinessWork owner = TransactionProxy.create(BusinessWork.class, () -> {
            notifications.create(1, NotificationType.MECHANIC_APPLICATION_APPROVED, "Approved", "Welcome");
            try { assertEquals(0, count()); }
            catch (SQLException e) { throw new IllegalStateException(e); }
            throw new IllegalStateException("business failed after collaborator returned");
        });
        assertThrows(IllegalStateException.class, owner::run);
        assertDoesNotThrow(() -> assertEquals(0, count()));
    }

    @Test void caughtCollaboratorFailureStillPreventsOwnerCommit() throws Exception
    {
        NotificationWriterOperations notifications = NotificationService.getNotificationWriterImpl();
        BusinessWork owner = TransactionProxy.create(BusinessWork.class, () -> {
            notifications.create(1, NotificationType.MECHANIC_APPLICATION_APPROVED, "Approved", "Welcome");
            assertThrows(RuntimeException.class, () -> notifications.create(2, NotificationType.MECHANIC_APPLICATION_APPROVED, null, "invalid title"));
        });
        assertThrows(RuntimeException.class, owner::run);
        assertEquals(0, count());
    }
}
